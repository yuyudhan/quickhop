#!/usr/bin/env python3
"""Regenerates crates/quickhop-providers/data/emoji-keywords.tsv from Unicode CLDR.

Usage: scripts/gen-emoji-keywords.py CLDR_CHECKOUT
Reads common/annotations/en.xml and common/annotationsDerived/en.xml and writes one
line per emoji: the glyph, a tab, and its CLDR keywords joined by "|". Skin-tone
variants are skipped; the provider shows base emoji only.
"""
import pathlib
import sys
import xml.etree.ElementTree as ET

SKIN_TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}


def read(path):
    keywords = {}
    for node in ET.parse(path).getroot().iter("annotation"):
        if node.get("type") == "tts":
            continue
        glyph = node.get("cp")
        if any(c in SKIN_TONES for c in glyph) and len(glyph) > 1:
            continue
        words = [w.strip() for w in (node.text or "").split("|") if w.strip()]
        keywords.setdefault(glyph, words)
    return keywords


def main():
    root = pathlib.Path(sys.argv[1]) / "common"
    keywords = read(root / "annotations" / "en.xml")
    for glyph, words in read(root / "annotationsDerived" / "en.xml").items():
        keywords.setdefault(glyph, words)
    out = pathlib.Path(__file__).resolve().parent.parent
    out = out / "crates" / "quickhop-providers" / "data" / "emoji-keywords.tsv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as file:
        file.write("# Generated by scripts/gen-emoji-keywords.py from Unicode CLDR (Unicode-3.0 licence).\n")
        for glyph in sorted(keywords):
            file.write(f"{glyph}\t{'|'.join(keywords[glyph])}\n")


if __name__ == "__main__":
    main()
